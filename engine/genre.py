def _opening_guidance(chapter_num: int) -> str:
    """Dynamic guidance for early chapters (黄金三章 + 第7章留存节点)."""
    if chapter_num == 1:
        return (
            "## 第1章特别指导（黄金三章·开篇）\n"
            "- 首句必须是事件/动作/信息炸弹，禁止环境描写开头，前3句主语不能是环境物件。\n"
            "- 主角必须在前300字内出场，出场人数 ≤ 4人。\n"
            "- 核心冲突/困境必须在本章内浮现。\n"
            "- 用行动展示人设，不用形容词定义——读者通过主角在压力下的选择认识主角。\n"
            "- 章末必须是最强级别钩子（悬念/危机/反转），让读者不得不翻下一章。"
        )
    if chapter_num == 2:
        return (
            "## 第2章特别指导（黄金三章·情绪爆点）\n"
            "- 第一个爽点必须在本章兑现（打脸/危机化解/能力首秀/系统首秀）。\n"
            "- 主角的核心目标/动机必须在本章明确——读者读完本章要知道主角想要什么。\n"
            "- 至少一段高质量对话，让主角的声音区别于其他角色。\n"
            "- 人设多面性开始展现（强大但有弱点、冷酷但有柔软处）。"
        )
    if chapter_num == 3:
        return (
            "## 第3章特别指导（黄金三章·期待建立）\n"
            "- 金手指/核心优势正式展示其潜力——读者看到主角未来能多强。\n"
            "- 世界观第一层揭示（但只揭一层，留更多层做悬念）。\n"
            "- 建立长线期待：更大的危机/更大的世界/更强的对手在远处等着。\n"
            "- 章末钩子必须是全书级别的大钩子，让读者决定追读。"
        )
    if chapter_num <= 7:
        return (
            "## 前7章留存强化指导\n"
            "- 每章至少1个爽点，钩子强度保持最强级别。\n"
            "- 信息投放密度：每1000字至少1个新信息（角色/世界观/能力/关系）。\n"
            "- 到第7章读者需要：主角人设完全立住、核心人际关系网络建立、"
            "第一轮爽点循环完成（铺垫→高潮→余韵）、至少一个次要悬念已解答。"
        )
    return ""
